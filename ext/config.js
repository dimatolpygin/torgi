// Настройки, которые заполняет РАЗРАБОТЧИК перед тем, как отдать расширение клиентке.
// В панели их нет намеренно: человеку, который бронирует место на рынке, незачем видеть
// адреса серверов и общие слова — он должен видеть только «готово / сделай вот это».
//
// Итог ночи в Telegram. Пока адрес пуст, расширение никуда его не шлёт и в панели про
// Telegram нет ни строчки. Чтобы включить:
//   1) вписать сюда адрес нашего приёмника и общее слово;
//   2) добавить ЭТОТ ЖЕ адрес в "host_permissions" манифеста (одним адресом, не звёздочкой).
var REPORT_URL = '';
var REPORT_SECRET = '';

// Боевая подача. true = в 00:00 расширение действительно отправляет заявки на сайт.
// Так оно и должно уезжать к клиентке: расширение, которое молча ничего не подаёт, —
// худший из возможных исходов ночи. false нужен ровно одному человеку — разработчику,
// который гоняет расширение в настоящем браузере и не хочет занять реальное место.
var LIVE_SUBMIT = true;

function reportConfigured() {
  return !!(REPORT_URL && REPORT_SECRET);
}

if (typeof module !== 'undefined' && module.exports) {
  module.exports = { REPORT_URL, REPORT_SECRET, LIVE_SUBMIT, reportConfigured };
}
